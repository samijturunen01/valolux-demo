/**
 * Prepares authentic Valolux imagery for the site.
 *
 * Source: images published on the company's current website (valolux.net),
 * incl. frames extracted from its Flash header (valolux.swf). Originals are kept
 * untouched in /source-assets for provenance. Output: optimised WebP files in
 * src/assets/media + a typed manifest (dimensions + tiny blurred placeholder).
 *
 * Run: npm run images
 */
import sharp from 'sharp';
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const SRC = join(root, 'source-assets/valolux-net');
const OUT = join(root, 'src/assets/media');
mkdirSync(OUT, { recursive: true });

// inset: px trimmed from each edge (old site photos carry a baked-in white rounded frame)
const items = [
  { key: 'autobaari', file: 'kohteet/kohde_01_autobaari_iso.jpg', inset: 12 },
  { key: 'puukeskus', file: 'flash/puukeskus.jpg', inset: 0 },
  { key: 'storaenso', file: 'flash/storaenso.jpg', inset: 0 },
  { key: 'pop-joensuu', file: 'kohteet/kohde_04_pankki_iso.jpg', inset: 12 },
  { key: 'lukkorengas', file: 'kohteet/kohde_05_lukkorengas_iso.jpg', inset: 12 },
  { key: 'kone-center', file: 'kohteet/kohde_06_konecenter_iso.jpg', inset: 12 },
  { key: 'lasermedia', file: 'kohteet/kohde_08_lasermedia_iso.jpg', inset: 12 },
  { key: 'solenovo', file: 'kohteet/kohde_09_solenovo_iso.jpg', inset: 12 },
  { key: 'karripojat', file: 'kohteet/kohde_10_karripojat_iso.jpg', inset: 12 },
  { key: 'delta-auto', file: 'kohteet/kohde_11_fiathuolto_iso.jpg', inset: 12 },
  { key: 'teippaus-kukka', file: 'kohteet/kohde_teippaus_01_iso.jpg', inset: 12 },
  { key: 'teippaus-fysio', file: 'kohteet/kohde_teippaus_03_iso.jpg', inset: 12 },
  { key: 'teippaus-kirja', file: 'kohteet/kohde_teippaus_04_iso.jpg', inset: 12 },
  { key: 'verstas', file: 'flash/verstas.jpg', inset: 0 },
  { key: 'pakettiauto', file: 'flash/pakettiauto.jpg', inset: 0 },
  { key: 'toimipiste', file: 'gfx/kuva_yritys.jpg', inset: 9 },
];

const manifest = [];
for (const it of items) {
  const img = sharp(join(SRC, it.file));
  const meta = await img.metadata();
  const w = meta.width - it.inset * 2;
  const h = meta.height - it.inset * 2;
  const base = sharp(join(SRC, it.file)).extract({ left: it.inset, top: it.inset, width: w, height: h });
  await base.clone().webp({ quality: 82, effort: 6 }).toFile(join(OUT, `${it.key}.webp`));
  const lqip = await base.clone().resize(20).blur(1.2).webp({ quality: 40 }).toBuffer();
  manifest.push({ key: it.key, w, h, lqip: `data:image/webp;base64,${lqip.toString('base64')}` });
  console.log(`${it.key.padEnd(16)} ${w}×${h}`);
}

const ident = (k) => k.replace(/-([a-z])/g, (_, c) => c.toUpperCase());
const ts = `// AUTO-GENERATED by scripts/prepare-images.mjs — do not edit by hand.
// Authentic imagery from valolux.net (see docs/RESEARCH.md for provenance).
${manifest.map((m) => `import ${ident(m.key)} from './${m.key}.webp';`).join('\n')}

export type MediaAsset = { src: string; w: number; h: number; lqip: string };

export const media = {
${manifest.map((m) => `  '${m.key}': { src: ${ident(m.key)}, w: ${m.w}, h: ${m.h}, lqip: '${m.lqip}' },`).join('\n')}
} satisfies Record<string, MediaAsset>;

export type MediaKey = keyof typeof media;
`;
writeFileSync(join(OUT, 'index.ts'), ts);
console.log(`\n${manifest.length} images → src/assets/media`);
